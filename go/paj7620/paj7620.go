// decodeGesture is grove.py's return_gesture(): read the flag register;
// a directional flag is held for GES_ENTRY_TIME and re-read, because a
// hand entering the field fires right/left/up/down before the driver can
// tell a forward/backward push. Returns the gesture code (0 = none).
// Reading and sleeping are injected so the decoding is unit-testable.
func decodeGesture(read func(reg uint8) (uint8, error), sleep func(d time.Duration)) (int, error) {
	data, err := read(paj7620Flag0)
	if err != nil {
		return 0, err
	}
	directional := map[uint8]int{
		gesRightFlag: 3,
		gesLeftFlag:  4,
		gesUpFlag:    5,
		gesDownFlag:  6,
	}
	if code, ok := directional[data]; ok {
		sleep(gesEntryTime)
		data, err = read(paj7620Flag0)
		if err != nil {
			return 0, err
		}
		switch data {
		case gesForwardFlag:
			sleep(gesQuitTime)
			return 1, nil
		case gesBackwardFlag:
			sleep(gesQuitTime)
			return 2, nil
		default:
			return code, nil
		}
	}
	switch data {
	case gesForwardFlag:
		sleep(gesQuitTime)
		return 1, nil
	case gesBackwardFlag:
		sleep(gesQuitTime)
		return 2, nil
	case gesClockwiseFlag:
		return 7, nil
	case gesAntiClockFlag:
		return 8, nil
	}
	data1, err := read(paj7620Flag1)
	if err != nil {
		return 0, err
	}
	if data1 == gesWaveFlag {
		return 9, nil
	}
	return 0, nil
}

// PAJ7620 reads gestures from a PAJ7620U2 on /dev/i2c-<bus> at 0x73.
type PAJ7620 struct {
	dev *common.I2CDevice
}

// NewPAJ7620 opens the sensor and runs the init sequence, waking the
// sensor if it does not answer: the PAJ7620 keeps its I2C interface
// powered down until bus activity wakes it, and does not acknowledge the
// transaction that does the waking — so the first register write of an
// unpoked sensor fails with EIO. Poke the bus, give the sensor a moment,
// and try again (like the Python node's _init_sensor).
func NewPAJ7620(bus int) (*PAJ7620, error) {
	dev, err := common.OpenI2C(bus, paj7620Addr)
	if err != nil {
		return nil, err
	}
	s := &PAJ7620{dev: dev}
	for attempt := 0; attempt < wakeAttempts; attempt++ {
		err = s.init()
		if err == nil {
			return s, nil
		}
		if attempt == wakeAttempts-1 {
			break
		}
		// One throwaway transaction wakes the sensor; it is itself not
		// acknowledged, so its error is expected and ignored.
		s.dev.ReadReg(0x00)
		time.Sleep(50 * time.Millisecond)
	}
	dev.Close()
	return nil, fmt.Errorf(
		"PAJ7620 did not respond on i2c bus %d (%v). Check the wiring and that the sensor appears at 0x73", bus, err)
}

// init is grove.py's init(): select bank 0 (twice, the second select
// covers a sensor that ignored the waking first one), verify the part id
// and write the whole init register table.
func (s *PAJ7620) init() error {
	time.Sleep(time.Millisecond)
	if err := s.dev.WriteReg(paj7620BankSel, 0); err != nil {
		return err
	}
	if err := s.dev.WriteReg(paj7620BankSel, 0); err != nil {
		return err
	}
	data0, err := s.dev.ReadReg(0)
	if err != nil {
		return err
	}
	if _, err := s.dev.ReadReg(1); err != nil {
		return err
	}
	// grove.py only warns on an unexpected part id and carries on.
	if data0 != 0x20 {
		fmt.Println("Error with sensor")
	} else {
		fmt.Println("wake-up finish.")
	}
	for _, entry := range initRegisterTable {
		if err := s.dev.WriteReg(entry[0], entry[1]); err != nil {
			return err
		}
	}
	if err := s.dev.WriteReg(paj7620BankSel, 0); err != nil {
		return err
	}
	fmt.Println("Paj7620 initialize register finished.")
	return nil
}

// ReadGesture returns the detected gesture name, or "" if nothing
// happened.
func (s *PAJ7620) ReadGesture() (string, error) {
	code, err := decodeGesture(s.dev.ReadReg, time.Sleep)
	if err != nil {
		return "", err
	}
	return gestureNames[code], nil
}

func (s *PAJ7620) Close() error { return s.dev.Close() }
